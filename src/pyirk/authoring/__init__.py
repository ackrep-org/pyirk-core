# Module mutation + validation


_END_MOD_RE = re.compile(r"^p\.end_mod\(\s*\)\s*$", re.MULTILINE)


def append_to_module(path: Path, code_block: str) -> None:
    """Insert ``code_block`` immediately before the closing ``p.end_mod()``."""
    path = Path(path)
    txt = path.read_text()
    matches = list(_END_MOD_RE.finditer(txt))
    if not matches:
        raise RuntimeError(f"target module {path} has no `p.end_mod()` line")
    pos = matches[-1].start()
    code = code_block.rstrip()
    new_txt = txt[:pos].rstrip() + "\n\n\n" + code + "\n\n\n" + txt[pos:]
    path.write_text(new_txt)


def validate_module(path: Path) -> Tuple[bool, str]:
    """Round-trip: re-load the module via irkloader. ``reuse_loaded=False`` so
    the change is actually re-executed, not silently skipped."""
    try:
        irkloader.load_mod_from_path(str(path), prefix="_validate", reuse_loaded=False)
        return True, ""
    except Exception as exc:
        return False, f"{type(exc).__name__}: {exc}"


# ---------------------------------------------------------------------------
# Claude invocation + response parsing


def propose_via_claude(prompt: str, timeout: int = 600, model: str = "sonnet") -> ClaudeCallResult:
    """Invoke ``claude -p`` and return the response text plus usage metadata.

    Uses ``--output-format json`` so the CLI reports its API-equivalent cost
    per call (``total_cost_usd``) -- the basis for the ``cost_usd`` fields in
    bulk-run stats. Raises ``RuntimeError`` if the subprocess fails or the CLI
    reports an error result (e.g. a session limit)."""
    cmd = ["claude", "-p", prompt, "--output-format", "json", "--model", model]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    if result.returncode != 0:
        # On CLI-level errors stderr is often empty, but the json envelope (if
        # any) carries the human-readable reason, e.g. "You've hit your
        # session limit ... resets 2:10am".
        detail = _claude_error_detail(result.stdout) or result.stderr[:500]
        raise RuntimeError(f"`claude -p` exited {result.returncode}: {detail}")
    return _parse_claude_cli_json(result.stdout)


def _claude_error_detail(stdout: str) -> str:
    try:
        return str(json.loads(stdout).get("result", ""))[:500]
    except (json.JSONDecodeError, AttributeError):
        return ""


def _parse_claude_cli_json(stdout: str) -> ClaudeCallResult:
    """Parse the ``--output-format json`` envelope of ``claude -p``."""
    try:
        payload = json.loads(stdout)
    except json.JSONDecodeError:
        # Defensive: treat unparseable output as bare response text so a CLI
        # that ignores --output-format degrades to cost-less operation.
        return ClaudeCallResult(text=stdout)
    if payload.get("is_error"):
        raise RuntimeError(f"`claude -p` reported an error result: {str(payload.get('result'))[:500]}")
    dur_ms = payload.get("duration_api_ms")
    return ClaudeCallResult(
        text=payload.get("result") or "",
        cost_usd=payload.get("total_cost_usd"),
        duration_api_s=round(dur_ms / 1000, 1) if dur_ms else None,
        session_id=payload.get("session_id") or "",
        num_turns=payload.get("num_turns"),
    )


_CODE_BLOCK_RE = re.compile(r"```(?:python)?\s*\n(.*?)```", re.DOTALL)
_FORK_LINE_RE = re.compile(r"^\s*\(([a-z])\)\s*(.+?)\s*$", re.MULTILINE)


def parse_response(text: str) -> ProposalResult:
    """Parse a structured Claude response.

    The prompt instructs Claude to respond with one of:

    * ``OK:`` followed by a fenced python code block.
    * ``FORK:`` followed by ``Q: <question>`` and labelled options
      ``  (a) ...`` / ``  (b) ...`` / ``  (c) ...``.

    Anything else is reported as ``ERROR`` so the caller can re-prompt.
    """
    stripped = text.lstrip()
    if stripped.upper().startswith("FORK"):
        q_match = re.search(r"^\s*Q:\s*(.+?)\s*$", text, re.MULTILINE)
        options = _FORK_LINE_RE.findall(text)
        if q_match and options:
            return ProposalResult(
                kind="FORK",
                question=q_match.group(1),
                options=options,
                raw=text,
            )
        return ProposalResult(kind="ERROR", raw=text)

    code_match = _CODE_BLOCK_RE.search(text)
    if code_match:
        return ProposalResult(kind="OK", code=code_match.group(1).strip(), raw=text)
    return ProposalResult(kind="ERROR", raw=text)


