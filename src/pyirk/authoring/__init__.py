"""Generic LLM-assisted authoring substrate for pyirk content modules.

This is the Claude-Code-native, lightweight variant of the MCP-based
authoring server sketched in ``docs/design/mcp_authoring.md``. Same value
props (retrieval-first; round-trip validation; structured append; explicit
modeling-fork escalation), simpler mechanics: a Python API plus a
subprocess call to ``claude -p``, instead of an MCP transport.

Source-specific extraction adapters (e.g. ``pyirk.authoring.lean``) sit on
top of this core. Adding a new source format means writing a new adapter,
not changing the core.
"""

from __future__ import annotations

import json
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Iterator, Optional, Tuple

from .. import core
from .. import irkloader

# ---------------------------------------------------------------------------
# Data classes


@dataclass
class EntityHit:
    """A retrieval result: an existing entity that could be reused or referenced."""

    short_key: str
    uri: str
    label: str
    description: str
    score: float = 0.0


@dataclass
class ProposalResult:
    """Result of an LLM proposal attempt."""

    kind: str  # "OK" or "FORK" or "ERROR"
    code: str = ""  # populated when kind == "OK"
    question: str = ""  # populated when kind == "FORK"
    options: list = field(default_factory=list)  # list[(letter, description)]
    raw: str = ""  # raw LLM response (for debugging / re-prompting)


@dataclass
class ClaudeCallResult:
    """Outcome of one ``claude -p`` invocation: response text plus usage metadata.

    ``cost_usd`` is the API-equivalent cost reported by the CLI
    (``total_cost_usd``); under subscription billing it is notional, but it is
    the right unit for usage accounting either way."""

    text: str
    cost_usd: Optional[float] = None
    duration_api_s: Optional[float] = None
    session_id: str = ""
    num_turns: Optional[int] = None


class ForkPending(Exception):
    """Raised by a non-interactive ``ask_user`` callback to signal that a FORK
    question cannot be answered in this run and the statement should be
    skipped (recorded as pending) instead of resolved arbitrarily."""

    def __init__(self, question: str, options: list):
        self.question = question
        self.options = options
        super().__init__(question)


# ---------------------------------------------------------------------------
# Session


@dataclass
class Session:
    """Holds the loaded pyirk state plus the working module path."""

    loaded_mods: dict = field(default_factory=dict)
    working_module_path: Optional[Path] = None
    working_module_prefix: str = ""

    def load_dependency(self, path: str, prefix: str):
        mod = irkloader.load_mod_from_path(path, prefix=prefix)
        self.loaded_mods[prefix] = mod
        return mod

    def all_entities(self) -> Iterator:
        for it in core.ds.items.values():
            yield it
        for r in core.ds.relations.values():
            yield r

    def dependency_label_index(self) -> str:
        """Flat label index of every entity defined in a loaded dependency.

        Helps the LLM reuse entities the lexical retrieval missed. Skips
        auto-generated scope artifacts (short keys with a lowercase second
        char like ``Ia12345`` / ``Ra...``) since they are scope-internal
        bookkeeping, not reusable concepts.
        """
        lines = []
        for prefix, mod in self.loaded_mods.items():
            dep_uri = getattr(mod, "__URI__", None)
            if not dep_uri:
                continue
            lines.append(f"  [prefix {prefix}, URI {dep_uri}]")
            entities = []
            for ent in self.all_entities():
                if getattr(ent, "base_uri", None) != dep_uri:
                    continue
                sk = ent.short_key
                # ``Ia...`` / ``Ra...`` are autogenerated scope-internal keys
                if len(sk) > 1 and sk[1].islower():
                    continue
                entities.append((sk, getattr(ent, "R1", "") or ""))
            entities.sort()
            for sk, lab in entities:
                lines.append(f'    - {sk} "{lab}"')
        return "\n".join(lines) if lines else "  (no dependencies loaded)"

    def search_entities(self, query: str, top_k: int = 10) -> list:
        """Cheap lexical scoring over label + description.

        For the pilot scale this is enough; the MCP design adds embeddings,
        but they only pay off at larger volume (see mcp_authoring.md sec. 5).
        """
        terms = [t for t in re.split(r"\W+", query.lower()) if len(t) > 1]
        hits = []
        for ent in self.all_entities():
            label = (getattr(ent, "R1", "") or "").lower()
            desc = (getattr(ent, "R2", "") or "").lower()
            if not (label or desc):
                continue
            score = sum(3 for t in terms if t in label) + sum(1 for t in terms if t in desc)
            if score <= 0:
                continue
            hits.append(
                EntityHit(
                    short_key=ent.short_key,
                    uri=ent.uri,
                    label=getattr(ent, "R1", "") or "",
                    description=(getattr(ent, "R2", "") or "")[:140],
                    score=score,
                )
            )
        hits.sort(key=lambda h: -h.score)
        return hits[:top_k]


