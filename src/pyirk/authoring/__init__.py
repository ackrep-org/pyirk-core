# Utilities


_ITEM_DECL_RE = re.compile(
    r"^(I\d+)\s*=\s*p\.create_item\(\s*\n\s*R1__has_label=[\"']([^\"']+)[\"']",
    re.MULTILINE,
)


def summarize_module(path: Path, max_items: int = 50) -> str:
    """Brief listing of existing top-level ``IXXXX = create_item(...)`` items."""
    txt = Path(path).read_text()
    items = _ITEM_DECL_RE.findall(txt)
    return "\n".join(f'  - {key} "{label}"' for key, label in items[:max_items])


_URI_RE = re.compile(r"__URI__\s*=\s*[\"\']([^\"\']+)[\"\']")


def extract_module_uri(path: Path) -> str:
    m = _URI_RE.search(Path(path).read_text())
    if not m:
        raise RuntimeError(f"module {path} has no __URI__")
    return m.group(1)


# ---------------------------------------------------------------------------
# Key-collision remapping


_DECL_ITEM_SIMPLE_RE = re.compile(r"^(I\d+)\s*=\s*p\.create_item\(", re.MULTILINE)
_DECL_REL_SIMPLE_RE = re.compile(r"^(R\d+)\s*=\s*p\.create_relation\(", re.MULTILINE)
_DECL_ANY_KEY_RE = re.compile(r"^([IR]\d+)\s*=", re.MULTILINE)


def _collect_occupied_keys(working_module_path: Path) -> set:
    """Return all known short keys: core.ds (builtins + loaded deps) + declarations in working module."""
    occupied = set()
    for ent in core.ds.items.values():
        occupied.add(ent.short_key)
    for ent in core.ds.relations.values():
        occupied.add(ent.short_key)
    txt = Path(working_module_path).read_text()
    for m in _DECL_ANY_KEY_RE.finditer(txt):
        occupied.add(m.group(1))
    return occupied


def remap_colliding_keys(code: str, occupied) -> tuple:
    """Remap declared keys in *code* that collide with *occupied*.

    Returns ``(new_code, mapping)`` where *mapping* is ``old_key -> new_key``.
    When nothing collides the returned code is byte-identical to the input and
    *mapping* is an empty dict.

    Replacement is deterministic: the numeric part is incremented from the
    original value until a key is free in ``occupied ∪ all_declared ∪ chosen``.

    Only top-level ``IXXXX = p.create_item(`` and ``RXXXX = p.create_relation(``
    declarations are considered.  For each remapped key all occurrences are
    updated: the assignment target, the label-reference form ``KEY["..."]``, and
    (for declared relations) the kwarg form ``KEY__attr_name=``.  Prefixed
    cross-module references (``ma__RXXXX``, ``a.ma__RXXXX``) are left untouched
    because the key is preceded by a word character or dot, which the negative
    lookbehind ``(?<![.\\w])`` rejects.
    """
    occupied = set(occupied)
    declared_items = [m.group(1) for m in _DECL_ITEM_SIMPLE_RE.finditer(code)]
    declared_rels = [m.group(1) for m in _DECL_REL_SIMPLE_RE.finditer(code)]
    declared_rels_set = set(declared_rels)
    all_declared = set(declared_items) | declared_rels_set

    # prevent replacements from colliding with other block-declared keys
    full_occupied = occupied | all_declared

    mapping: dict = {}
    chosen: set = set()  # replacement keys already picked in this pass

    for key in declared_items + declared_rels:
        if key not in occupied:
            continue
        prefix = key[0]
        num = int(key[1:]) + 1
        while True:
            candidate = f"{prefix}{num}"
            if candidate not in full_occupied and candidate not in chosen:
                mapping[key] = candidate
                chosen.add(candidate)
                break
            num += 1

    if not mapping:
        return code, {}

    new_code = code
    for old_key, new_key in mapping.items():
        pat = re.escape(old_key)
        # 1. assignment target: KEY at start of line followed by =
        new_code = re.sub(r"(?m)^" + pat + r"(?=\s*=)", new_key, new_code)
        # 2. label-reference form: KEY["..."] not preceded by . or \w
        new_code = re.sub(r"(?<![.\w])" + pat + r"(?=\[)", new_key, new_code)
        # 3. kwarg form of a declared relation: KEY__attr_name= not preceded by . or \w
        if old_key in declared_rels_set:
            new_code = re.sub(r"(?<![.\w])" + pat + r"(?=__)", new_key, new_code)

    return new_code, mapping


# ---------------------------------------------------------------------------
# Guards for the non-collision failure classes (see bulk_runs2/SUMMARY.md)

# String literals (incl. triple-quoted, optional prefix) and comments. Their
# contents may legitimately hold non-ASCII (math labels/descriptions), so they
# are masked out before scanning the *code* for stray Lean operators.
_STRING_OR_COMMENT_RE = re.compile(
    r"""[rbfuRBFU]{0,3}(?:\"\"\".*?\"\"\"|'''.*?'''|"(?:\\.|[^"\\\n])*"|'(?:\\.|[^'\\\n])*')""" r"|#[^\n]*",
    re.DOTALL,
)


def _mask_strings_and_comments(code: str) -> str:
    """Blank out string-literal and comment spans (keeping newlines) so the
    remaining text has valid line/column coordinates for the real code only."""
    return _STRING_OR_COMMENT_RE.sub(lambda m: "".join(c if c == "\n" else " " for c in m.group(0)), code)


def find_nonascii_outside_strings(code: str) -> list:
    """Return ``[(lineno, col, char), ...]`` for non-ASCII characters in actual
    code (outside string literals and comments).

    Such characters are almost always Lean operators (``→``, ``∘``, ``•``,
    ``≤`` …) transcribed verbatim into the Python block; they raise a cryptic
    ``SyntaxError`` only at module re-load. Detecting them up front lets the
    pipeline re-prompt with a precise message instead.
    """
    masked = _mask_strings_and_comments(code)
    hits = []
    for lineno, line in enumerate(masked.splitlines(), start=1):
        for col, ch in enumerate(line, start=1):
            if ord(ch) > 127:
                hits.append((lineno, col, ch))
    return hits


_SCOPE_OPEN_RE = re.compile(r"^\s*with\s+([IR]\d+)\s*\[", re.MULTILINE)


def find_reopened_scopes(code: str) -> list:
    """Return the distinct keys that *code* opens a ``.scope(...)`` on without
    declaring them in the same block.

    Opening ``with KEY[...].scope(...)`` on a KEY not created by a
    ``create_item`` / ``create_relation`` in this very block re-uses a theorem
    item from an earlier statement, which raises ``InvalidScopeNameError`` (the
    item already owns its scopes). Every theorem must own a fresh item.
    """
    declared = {m.group(1) for m in _DECL_ITEM_SIMPLE_RE.finditer(code)}
    declared |= {m.group(1) for m in _DECL_REL_SIMPLE_RE.finditer(code)}
    reopened, seen = [], set()
    for m in _SCOPE_OPEN_RE.finditer(code):
        key = m.group(1)
        if key not in declared and key not in seen:
            seen.add(key)
            reopened.append(key)
    return reopened


# ---------------------------------------------------------------------------
# Generic import loop (shared by all source adapters)


def import_one_statement(
    *,
    session: Session,
    theorem_text: str,
    source_info: str,
    working_module_path: Path,
    ask_user: Callable[[str, list], str],
    extra_query_text: str = "",
    max_attempts: int = 3,
    claude_timeout: int = 600,
    on_progress: Optional[Callable[[str], None]] = None,
    events: Optional[list] = None,
) -> Tuple[bool, str]:
    """Drive one statement through retrieval → propose → escalate → validate.

    Returns ``(ok, message)``. If ``events`` is a list, structured per-attempt
    records (dicts) are appended to it -- the basis for bulk-run metrics
    (FORK rate, validation-retry rate etc.).
    """
    log = on_progress or (lambda msg: None)
    if events is None:
        events = []  # discard silently; keeps the append sites unconditional

    query = " ".join(filter(None, [theorem_text, extra_query_text, source_info]))
    hits = session.search_entities(query, top_k=15)
    log(f"retrieval: {len(hits)} hits")

    working_summary = summarize_module(working_module_path)
    working_uri = extract_module_uri(working_module_path)
    dependency_index = session.dependency_label_index()

    extra_context = ""
    for attempt in range(1, max_attempts + 1):
        prompt = build_import_prompt(
            theorem_text=theorem_text,
            source_info=source_info,
            retrieval_hits=hits,
            dependency_index=dependency_index,
            working_summary=working_summary,
            working_module_uri=working_uri,
            loaded_prefixes=list(session.loaded_mods.keys()),
            extra_context=extra_context,
        )
        log(f"attempt {attempt}: calling claude")
        try:
            raw = propose_via_claude(prompt, timeout=claude_timeout)
        except subprocess.TimeoutExpired:
            # A timeout used to propagate out and kill the whole theorem as a
            # fatal "error" with no retry. Treat it as a retryable attempt
            # instead. (Note: with the default 600 s, up to max_attempts
            # timeouts can exceed an outer worker timeout -- that is fine, the
            # idempotent --resume picks the theorem up again next run.)
            events.append({"event": "timeout", "attempt": attempt, "timeout_s": claude_timeout})
            log(f"claude call timed out after {claude_timeout}s")
            extra_context = (
                f"Your previous attempt did not return within {claude_timeout} "
                "seconds and was aborted. Produce the MINIMAL correct encoding: "
                "no prose, keep the code block as small as the theorem allows."
            )
            continue
        if isinstance(raw, str):
            # test mocks and other stand-ins may return bare response text
            raw = ClaudeCallResult(text=raw)
        # per-call usage, attached to whichever event this attempt produces
        usage = {"cost_usd": raw.cost_usd} if raw.cost_usd is not None else {}
        result = parse_response(raw.text)

        if result.kind == "FORK":
            log(f"FORK: {result.question}")
            try:
                choice = ask_user(result.question, result.options)
            except ForkPending:
                # still account for the claude call that surfaced the fork
                events.append(
                    {"event": "fork_pending", "attempt": attempt, "question": result.question, **usage}
                )
                raise
            events.append(
                {
                    "event": "fork",
                    "attempt": attempt,
                    "question": result.question,
                    "options": list(result.options),
                    "choice": choice,
                    **usage,
                }
            )
            extra_context = (
                f"User resolved a previous modeling fork.\n"
                f"Question: {result.question}\n"
                f"Chosen option: ({choice})\n"
                f"Now produce the OK response."
            )
            continue

        if result.kind != "OK":
            events.append({"event": "malformed", "attempt": attempt, **usage})
            extra_context = (
                "Previous response was malformed -- it did not match either the "
                "OK or FORK output format. Try again, strictly following the "
                "output format. Raw previous response (excerpt):\n"
                f"{result.raw[:400]}"
            )
            continue

        # OK: remap colliding keys, then guard against the known non-collision
        # failure classes before the (expensive) round-trip validation.
        occupied = _collect_occupied_keys(working_module_path)
        code_to_append, remap = remap_colliding_keys(result.code, occupied)
        if remap:
            events.append({"event": "key_remap", "attempt": attempt, "mapping": remap})

        nonascii = find_nonascii_outside_strings(code_to_append)
        if nonascii:
            sample = ", ".join(f"{ch!r} (line {ln}, col {col})" for ln, col, ch in nonascii[:6])
            events.append(
                {"event": "nonascii", "attempt": attempt, "chars": [h[2] for h in nonascii], **usage}
            )
            log(f"non-ASCII in code: {sample}")
            extra_context = (
                "Your code block contains non-ASCII character(s) OUTSIDE string "
                f"literals: {sample}. These are Lean operators transcribed verbatim "
                "and are illegal in Python source. Rewrite using pyirk constructs: "
                "ASCII arithmetic on items (** + * for the overloaded operators), "
                "the appropriate operator/relation items for composition, ordering, "
                "membership etc., and never put symbols like the function arrow, "
                "ring/scalar dot, composition ring, <=, or set membership into the "
                "code. Non-ASCII is fine ONLY inside string labels/descriptions."
            )
            continue

        reopened = find_reopened_scopes(code_to_append)
        if reopened:
            keys = ", ".join(reopened)
            events.append({"event": "scope_reopen", "attempt": attempt, "keys": reopened, **usage})
            log(f"scope reopen on non-declared item(s): {keys}")
            extra_context = (
                f"Your code opens a scope (`with ...scope(...)`) on item(s) {keys} "
                "that are NOT created in this block. That re-uses a theorem item "
                "from an earlier statement and fails (the item already owns its "
                "scopes). Every theorem needs its OWN new `create_item(...)`; open "
                "scopes only on the freshly created theorem item of THIS statement."
            )
            continue

        backup = working_module_path.read_text()
        try:
            append_to_module(working_module_path, code_to_append)
        except Exception as exc:
            working_module_path.write_text(backup)
            events.append({"event": "append_fail", "attempt": attempt, "error": str(exc)[:300], **usage})
            extra_context = f"append_to_module failed: {exc}. Try again."
            continue

        ok, err = validate_module(working_module_path)
        if ok:
            log("validation OK")
            events.append({"event": "ok", "attempt": attempt, **usage})
            return True, "ok"
        # rollback + re-prompt with the validation error
        working_module_path.write_text(backup)
        events.append({"event": "validation_fail", "attempt": attempt, "error": err[:300], **usage})
        extra_context = (
            "Previous attempt was syntactically appended but failed "
            f"validation:\n{err[:600]}\n"
            "Diagnose the error and produce a corrected OK response."
        )
        log(f"validation FAIL: {err[:120]}")

    events.append({"event": "gave_up", "attempts": max_attempts})
    return False, f"gave up after {max_attempts} attempts"


_BOOTSTRAP_TEMPLATE = '''\
"""Auto-generated pyirk content module for theorem import."""

import pyirk as p

ma = p.irkloader.load_mod_from_path({ocse_path!r}, prefix="ma")

__URI__ = "{uri}"
keymanager = p.KeyManager()
p.register_mod(__URI__, keymanager)
p.start_mod(__URI__)


R9999 = p.create_relation(
    R1__has_label="has source reference",
    R2__has_description="verbatim source identifier of an imported statement",
)


p.end_mod()
'''


def bootstrap_working_module(path, uri: str, ocse_path: str) -> Path:
    """Create a fresh pyirk content module at ``path`` with the standard bootstrap.

    The bootstrap declares ``R9999["has source reference"]`` so the prompt rules
    can reference it (see ``PROMPT_RULES``). Subsequent theorem appends use
    :func:`append_to_module`, which inserts before the closing ``p.end_mod()``.
    """
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    txt = _BOOTSTRAP_TEMPLATE.format(uri=uri, ocse_path=str(ocse_path))
    path.write_text(txt)
    return path


def ask_user_via_stdin(question: str, options: list) -> str:
    """Default interactive escalation -- prompt on stdin/stdout."""
    print()
    print(question)
    for letter, desc in options:
        print(f"  ({letter}) {desc}")
    while True:
        choice = input("Your choice: ").strip().lower()
        if any(choice == letter for letter, _ in options):
            return choice
        print(f"  please pick one of: {', '.join(letter for letter, _ in options)}")


def fork_policy_first(question: str, options: list) -> str:
    """Non-interactive FORK policy: always pick the first offered option.

    For unattended bulk runs. The arbitrary-but-documented choice keeps the
    import going; the question/options/choice are recorded in the per-theorem
    event log so the decision can be audited later.
    """
    if not options:
        raise ValueError(f"FORK question offered no options: {question!r}")
    return options[0][0]


def fork_policy_skip(question: str, options: list) -> str:
    """Non-interactive FORK policy: do not decide -- skip the statement.

    Raises :class:`ForkPending`; the caller records the theorem as pending
    instead of resolving the modeling ambiguity arbitrarily.
    """
    raise ForkPending(question, options)
