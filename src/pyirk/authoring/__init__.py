PROMPT_HEADER = """You are mapping the *statement* of a formal theorem into a pyirk content
module. Proofs are explicitly out of scope -- pyirk represents statements
only. Reuse existing entities aggressively; only introduce a new local
item if no entity in the listings below matches the needed concept.

CRITICAL: your output is *appended* to a working module that is already
fully bootstrapped. The module already executes ``import pyirk as p``,
loads its dependencies (e.g. ``ma = p.irkloader.load_mod_from_path(...,
prefix="ma")``), and has called ``p.start_mod(__URI__)``. Do NOT include
``import pyirk``, ``load_mod_from_path``, ``KeyManager``, ``register_mod``,
``start_mod``, or ``end_mod`` in your code block. Produce ONLY the new
``create_item`` / ``create_relation`` / ``with ...scope(...) as st:`` blocks.

Canonical example: an iff theorem (Pythagorean theorem, sides form) in pyirk.
Treat this as the structure you must follow.

```python
# Local value type so operator and named constant share a meaningful type.
I999 = p.create_item(
    R1__has_label="angle (quantity)",
    R2__has_description="real-number-valued angle magnitude (radians)",
    R3__is_subclass_of=p.I35["real number"],
)
# Local operator (no match in deps).
I1000 = p.create_item(
    R1__has_label="angle",
    R2__has_description="binary operator: angle between two polygon sides",
    R4__is_instance_of=p.I8["mathematical operation with arity 2"],
    R8__has_domain_of_argument_1=ma.I8172["polygon side"],
    R9__has_domain_of_argument_2=ma.I8172["polygon side"],
    R11__has_range_of_result=I999["angle (quantity)"],
)
# Local named constant.
I1001 = p.create_item(
    R1__has_label="right angle",
    R2__has_description="constant: pi/2",
    R4__is_instance_of=I999["angle (quantity)"],
)
# The theorem (iff -> I17 equivalence proposition).
I5000 = p.create_item(
    R1__has_label="Pythagorean theorem (sides form)",
    R4__is_instance_of=p.I17["equivalence proposition"],
)
with I5000["Pythagorean theorem (sides form)"].scope("setting") as st:
    st.new_var(ta=p.uq_instance_of(ma.I2917["planar triangle"]))
    st.new_var(sides=ma.I9148["get polygon sides ordered by length"](st.ta))
    a, b, c = p.unpack_tuple_item(st.sides)
    la = a.ma__R2495__has_length
    lb = b.ma__R2495__has_length
    lc = c.ma__R2495__has_length
with I5000["Pythagorean theorem (sides form)"].scope("premise") as st:
    st.new_equation(lhs=I1000["angle"](a, b), rhs=I1001["right angle"])
with I5000["Pythagorean theorem (sides form)"].scope("assertion") as st:
    st.new_equation(lhs=la**2 + lb**2, rhs=lc**2)
```

Key idioms to copy from that example:
* Short keys MUST match ``IXXXX`` / ``RXXXX`` where XXXX is digits
  (e.g. ``I5000``, ``R2495``). Do NOT use descriptive Python names like
  ``I_distance_quantity``; the key resolver will reject them.
* ``R3__is_subclass_of`` is the class-of-class relation.
  ``R4__is_instance_of`` is the member-of-class relation. Do not confuse.
* Theorem statements use three scopes: ``setting`` (universally quantified
  variables and derived expressions), ``premise`` (assumed equation),
  ``assertion`` (concluded equation). For I17 (iff), premise/assertion
  are interchangeable in meaning but the syntactic split is still required.
* Inside a scope, use ``st.new_var(...)`` and ``st.new_equation(lhs=..., rhs=...)``.
  Do NOT call ``p.new_equation`` at module top-level.
* If the source theorem talks about three points / a vertex / a triangle in
  plane geometry, prefer reusing ``ma.I2917 planar triangle`` plus
  ``ma.I9148 get polygon sides ordered by length`` over inventing point and
  distance items from scratch.
"""


PROMPT_RULES = """Modeling rules (strict):
* The encoding must follow the *source* type signature. When the source
  theorem declares typed variables (e.g. ``(x y : V)`` in Lean with
  ``V`` constrained to be a vector space), declare them in the ``setting``
  scope as ``p.uq_instance_of(<entity matching V>)``. If a matching entity
  exists in the dependency index (e.g. ``ma.I7151["vector"]`` for a
  ``V : Vector``-style declaration), reuse it. Do NOT re-encode the source
  variables under a derived geometric structure (e.g. a triangle) just
  because the worked example below happens to use one.
* Use ``p.I17["equivalence proposition"]`` for a biconditional / iff ("↔", "<->").
* Use ``p.I15["implication proposition"]`` for a one-directional implication.
* Each source theorem maps to its OWN distinct ``create_item(...)`` with
  its own ``R1__has_label``, even when structurally similar to one already
  in the working module. Reuse applies to *concept entities* (operators,
  value types, constants) but NOT to *theorem identities*: a Lean iff
  theorem and its companion implication theorem are two distinct pyirk
  items (one I17, one I15). Do NOT re-open ``with <existing-theorem>.scope
  (...)`` to encode a second source theorem.
* Each new theorem item MUST carry a source-reference attribute using the
  working-module relation ``R9999["has source reference"]``. Set it as a
  kwarg on ``create_item``:
  ``R9999__has_source_reference="<source identifier>"``, where the
  identifier is the content of the ``Source:`` line at the top of this
  prompt copied verbatim (single line, including any ``(URL)`` suffix).
  This applies to every source theorem, including implication forms that
  are companions of an iff theorem.
* ``R9999`` is already declared in the working module bootstrap. Do NOT
  re-declare it (no ``R9999 = p.create_relation(...)`` in your code
  block); just reference it as a kwarg on theorem items.
* For cross-module relations use the prefix attribute form, e.g.
  ``a.ma__R2495__has_length`` (NOT ``a.R2495__has_length``).
* pyirk Items overload ``**``, ``+``, ``*``; write equations directly on
  items (e.g. ``la**2 + lb**2``). Do NOT use ``items_to_symbols``.
* Builtin arity items: ``p.I7["mathematical operation with arity 1"]``,
  ``p.I8["mathematical operation with arity 2"]``, ``p.I9["mathematical
  operation with arity 3"]``. The label MUST match the key, and the
  arity MUST match the operator's actual number of arguments. Common
  failure mode: writing ``p.I8["mathematical operation with arity 1"]``
  for a unary operator -- use ``p.I7`` for unary instead.
* The signature is ``new_equation(lhs=..., rhs=...)`` -- two args, not three.
* When you introduce a new local *value* type (e.g. "angle (quantity)"),
  make it ``R3__is_subclass_of`` the most specific applicable parent so
  the operator result and any named constants share a meaningful type.

FORK is MANDATORY (not optional) when introducing a new item whose
mapping has more than one plausible encoding. You MUST emit FORK,
not OK, in any of these cases:

* The source concept (e.g. ``arccos``, ``inner product``, a specific
  algebraic operator) could be modeled either as a stand-alone item OR
  as a member of a small family with siblings sharing a parent type
  ("inverse trigonometric function", "binary form on a vector space",
  ...). The choice between these is a fork.
* A needed entity could plausibly REUSE an existing one from the
  dependency index OR be a new local item with narrower / broader
  scope. The choice is a fork.
* The new item's parent class is not uniquely determined by the source
  (e.g. ``p.I7["mathematical operation with arity 1"]`` vs
  ``ma.I1060["general function"]`` vs a new local type). The choice is
  a fork.

Do NOT confidently pick one encoding and ship OK if any of the above
applies. The point of FORK is to surface modeling choices to a human;
fluent confidence in the OK path defeats it. When in doubt, FORK.

Output format (exactly one of these two; nothing else, no prose around):

OK:
```python
<one block of pyirk code to be appended to the working module>
```

FORK:
Q: <one short question describing the modeling fork>
  (a) <option a, including the entity reuse / creation choice>
  (b) <option b>
  (c) <option c, often "reuse existing entity X">
"""


def build_import_prompt(
    *,
    theorem_text: str,
    source_info: str,
    retrieval_hits: list,
    dependency_index: str,
    working_summary: str,
    working_module_uri: str,
    loaded_prefixes: list,
    extra_context: str = "",
) -> str:
    hits_block = (
        "\n".join(f'  - {h.short_key} "{h.label}" -- {h.description}' for h in retrieval_hits)
        or "  (no hits)"
    )
    prefix_block = ", ".join(loaded_prefixes) or "(only builtins)"
    re_prompt_block = (
        f"\nRE-PROMPT CONTEXT (apply this when producing the next response):\n{extra_context}\n"
        if extra_context
        else ""
    )
    return (
        PROMPT_HEADER
        + f"\nSource: {source_info}\n"
        + f"\nWorking module URI: {working_module_uri}\n"
        + f"Already-loaded dependency prefixes: {prefix_block}\n"
        + re_prompt_block
        + f"\nTheorem statement (verbatim):\n{theorem_text}\n"
        + f"\nRetrieval hits (top-scored {len(retrieval_hits)} candidates by lexical match):\n{hits_block}\n"
        + f"\nFull entity index of loaded dependencies (label-only, in case retrieval missed something):\n{dependency_index}\n"
        + f"\nExisting items in the working module:\n{working_summary or '  (empty)'}\n"
        + "\n"
        + PROMPT_RULES
    )


